/// Contains the additional data produced for each proving chunk, and needed by the verifier
#[derive(Clone, Serialize, Deserialize)]
#[serde(bound(
    serialize = "F: ark_serialize::CanonicalSerialize",
    deserialize = "F: ark_serialize::CanonicalDeserialize"
))]
pub(crate) struct ChunkProofData<F: PrimeField, PCS: CommitmentScheme> {
    /// Commitments to the incoming and outgoing edges of the chunk
    commitments: ChunkIOCommitments<VerifierCommitment<PCS>>,
    /// Evaluations of the polynomials corresponding to each port of the chunk's outgoing edges
    output_evals: BTreeMap<NodeOutput, PolynomialEvaluation<F>>,
    /// The chunk of the model this data refers to
    model_chunk: ModelChunk,
}

impl<F, PCS> Default for ChunkProofData<F, PCS>
where
    F: PrimeField,
    PCS: CommitmentScheme,
{
    fn default() -> Self {
        Self {
            commitments: ChunkIOCommitments::default(),
            output_evals: BTreeMap::default(),
            model_chunk: ModelChunk::default(),
        }
    }
}

/// All the cryptographic material generated by the prover for a given proven chunk
#[derive(Clone, Serialize, Deserialize)]
#[serde(bound(
    serialize = "F: ark_serialize::CanonicalSerialize",
    deserialize = "F: ark_serialize::CanonicalDeserialize"
))]
pub struct ChunkProof<F: PrimeField, PCS: CommitmentScheme> {
    /// The successive sumchecks proofs. From output layer to input.
    steps: HashMap<NodeId, LayerProof<F, PCS>>,
    /// Proofs to merge output claims of a node, if any
    merge_claim_proofs: HashMap<NodeId, MergeClaimsProof<F>>,
    /// The proofs for any lookup tables used
    table_proof: Option<TableProof<F, PCS>>,
    /// the commitment proofs related to the witness polynomial of the chunk
    commit: OpeningProof<F, PCS>,
    // data about the proven chunk
    chunk_data: ChunkProofData<F, PCS>,
}

impl<F, PCS> std::fmt::Debug for ChunkProof<F, PCS>
where
    F: PrimeField,
    PCS: CommitmentScheme,
{
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "ChunkProof {{ # steps: {:?}, # merge_claim_proofs: {:?}, table_proof ? {:?}, commit, chunk_data }}",
            self.steps.len(),
            self.merge_claim_proofs.len(),
            self.table_proof.is_some()
        )
    }
}

/// Contains all cryptographic material generated by the prover
#[derive(Clone, Serialize, Deserialize)]
#[serde(bound(
    serialize = "F: ark_serialize::CanonicalSerialize",
    deserialize = "F: ark_serialize::CanonicalDeserialize"
))]
pub struct Proof<F: PrimeField, PCS: CommitmentScheme> {
    /// the proof for each proven chunk
    chunk_proofs: Vec<ChunkProof<F, PCS>>,
}

impl<F: PrimeField, PCS: CommitmentScheme> std::fmt::Debug for Proof<F, PCS> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "Final Proof {{ # chunk_proofs: {:?}}}",
            self.chunk_proofs.len()
        )
    }
}

impl<F: PrimeField, PCS: CommitmentScheme> From<Vec<ChunkProof<F, PCS>>> for Proof<F, PCS> {
    fn from(chunk_proofs: Vec<ChunkProof<F, PCS>>) -> Self {
        Self { chunk_proofs }
    }
}

impl<F: PrimeField, PCS: CommitmentScheme> Proof<F, PCS> {
    pub fn num_chunks(&self) -> usize {
        self.chunk_proofs.len()
    }

    pub fn into_chunk_proofs(self) -> Vec<ChunkProof<F, PCS>> {
        self.chunk_proofs
    }
}

#[derive(Clone, Serialize, Deserialize)]
#[serde(bound(
    serialize = "F: ark_serialize::CanonicalSerialize",
    deserialize = "F: ark_serialize::CanonicalDeserialize"
))]
pub struct TableProof<F: PrimeField, PCS: CommitmentScheme> {
    /// The commitment to the multiplicity polynomials
    multiplicity_commit: Vec<VerifierCommitment<PCS>>,
    /// the lookup protocol proof for the table fractional sumcheck
    lookup: LogUpBatchProof<F>,
}

impl<F, PCS> TableProof<F, PCS>
where
    F: PrimeField,
    PCS: CommitmentScheme,
{
    /// gets a reference to the inner commitment
    pub fn get_commitments(&self) -> &[VerifierCommitment<PCS>] {
        &self.multiplicity_commit
    }

    pub(crate) fn write_commitments<T: Transcript>(&self, transcript: &mut T) {
        self.multiplicity_commit
            .iter()
            .for_each(|comm| comm.append_to_transcript(transcript))
    }
}

#[derive(Debug, Clone, Default)]
pub struct ChallengeStorage<F: PrimeField> {
    /// This is the constant challenge looked in the lookup PIOPs
    pub constant_challenge: F,
    /// This is the map containing different values related to different tables/lookups
    pub challenge_map: HashMap<String, F>,
}

impl<F> ChallengeStorage<F>
where
    F: PrimeField,
{
    pub fn initialise<T: Transcript>(ctx: &LookupContext, transcript: &mut T) -> Self {
        let constant_challenge = transcript.append_and_sample(b"table_constant");
        let challenge_map = ctx
            .iter()
            .map(|table_type| {
                let challenge = table_type.generate_challenge(transcript);
                (table_type.name(), challenge)
            })
            .collect::<HashMap<String, F>>();
        Self {
            constant_challenge,
            challenge_map,
        }
    }

    pub fn get_challenges_by_name(&self, name: &String) -> Option<(F, F)> {
        self.challenge_map
            .get(name)
            .map(|challenges| (self.constant_challenge, *challenges))
    }
}

pub(crate) fn compute_claim<F: PrimeField, T: Transcript>(
    transcript: &mut T,
    tensor: Tensor<F>,
) -> anyhow::Result<Claim<F>> {
    // Derive the first randomness
    let r_i = transcript.read_challenges(tensor.shape().num_vars().into_iter().sum());
    let y_i = tensor.into_mle().evaluate(&r_i)?;
    Ok(Claim {
        point: r_i,
        eval: y_i,
    })
}

#[cfg(test)]
mod test {
    use dp_crypto::arkyper::transcript::blake3::Blake3Transcript;
    use parking_lot::{RwLockWriteGuard, lock_api::RwLockUpgradableReadGuard};

    use crate::{
        graph::executor::{SequentialExecutor, ThreadPoolExecutor},
        init_test_logging, init_test_logging_default,
        iop::chunking::DefaultChunkingStrategy,
        layers::einsum,
        model::Model,
        testing::Pcs,
    };

    use super::{prover::Prover, verifier::verify};

    type F = ark_bn254::Fr;

    type T = Blake3Transcript;
    type P<'a, 'b> = Prover<'a, 'b, F, T, Pcs>;

    #[test]
    fn test_prover_steps_generic() {
        init_test_logging("debug");
        use crate::StdRng;
        use ark_std::rand::SeedableRng;
        let mut rng = StdRng::seed_from_u64(4);
        let (model, input) = Model::random_with_rng(4, &mut rng).unwrap();

        model.describe();
        let trace = model.run(input, &mut Default::default()).unwrap();
        let (prover_ctx, verifier_ctx) = model
            .generate_contexts::<F, Pcs>()
            .expect("unable to generate contexts");
        let (proof, io) = P::prove(&prover_ctx, trace, &model).expect("unable to generate proof");
        verify::<_, T, _>(&verifier_ctx, proof, io).expect("invalid proof");
    }

    #[test]
    fn test_prover_steps_pooling() {
        init_test_logging_default();
        let (model, input) = Model::random_pooling(4).unwrap();
        model.describe();
        let trace = model.run(input, &mut Default::default()).unwrap();
        let (prover_ctx, verifier_ctx) = model
            .generate_contexts::<F, Pcs>()
            .expect("unable to generate contexts");
        let (proof, io) = P::prove(&prover_ctx, trace, &model).expect("unable to generate proof");
        verify::<_, T, _>(&verifier_ctx, proof, io).expect("invalid proof");
    }

    #[test]
    fn test_distribute_prove() {
        init_test_logging("debug");
        let num_dense_layers = 5;
        let (model, inputs) = Model::random(num_dense_layers).unwrap();
        model.describe();
        let trace = model.run(inputs, &mut Default::default()).unwrap();
        let (prover_ctx, verifier_ctx) = model
            .generate_contexts::<F, Pcs>()
            .expect("unable to generate contexts");
        let chunking_strategy = DefaultChunkingStrategy::from(&trace);
        let (proof, io) = P::chunked_prove_local::<_, ThreadPoolExecutor>(
            &prover_ctx,
            trace,
            Some(3),
            chunking_strategy,
            &model,
            (),
        )
        .expect("unable to generate proof");
        verify::<_, T, _>(&verifier_ctx, proof, io).expect("invalid proof");
    }

    #[test]
    fn test_distribute_prove_horizontal_chunking() {
        let mut lock = einsum::MIN_CHUNK_SIZE.write();
        lock.replace(4); // set the minimum chunk size to 4 to force horizontal chunking on small inputs

        // downgrade to read lock to prevent any other test thread to change `MIN_CHUNK_SIZE` while this test is running
        let read_lock = RwLockWriteGuard::downgrade_to_upgradable(lock);
        init_test_logging("debug");

        let num_linear_layers = 6;
        let (model, inputs) = Model::random_with_matmul(num_linear_layers, 17..63).unwrap();
        model.describe();
        let trace = model.run(inputs, &mut Default::default()).unwrap();
        let (prover_ctx, verifier_ctx) = model
            .generate_contexts::<F, Pcs>()
            .expect("unable to generate contexts");
        let chunking_strategy = DefaultChunkingStrategy::from(&trace);
        let (proof, io) = P::chunked_prove_local::<_, SequentialExecutor>(
            &prover_ctx,
            trace,
            Some(12),
            chunking_strategy,
            &model,
            (),
        )
        .expect("unable to generate proof");
        verify::<_, T, _>(&verifier_ctx, proof, io).expect("invalid proof");

        RwLockUpgradableReadGuard::upgrade(read_lock).take();
    }
}
